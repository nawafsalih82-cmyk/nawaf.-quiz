// Helper to prepare randomized questions for a given level
export function getPreparedQuestions(level: LevelId): Question[] {
  const filtered = RAW_QUESTIONS.filter((q) => q.level === level);

  // Shuffle array using Fisher-Yates
  const shuffledQuestions = [...filtered].sort(() => Math.random() - 0.5);

  // Take exactly 20 questions
  const selected20 = shuffledQuestions.slice(0, 20);

  // Randomize answer choices order while keeping correct answer associated
  return selected20.map((item) => {
    const correctText = item.options[item.correctIndex];
    const shuffledOptions = [...item.options].sort(() => Math.random() - 0.5);
    const newCorrectIndex = shuffledOptions.indexOf(correctText);

    return {
      ...item,
      options: shuffledOptions,
      correctIndex: newCorrectIndex
    };
  });
}
