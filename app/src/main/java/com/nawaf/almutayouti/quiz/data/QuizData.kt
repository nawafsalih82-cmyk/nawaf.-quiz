    fun getQuestionsForLevel(level: DifficultyLevel): List<QuizQuestion> {
        val baseList = when (level) {
            DifficultyLevel.EASY -> level1Questions
            DifficultyLevel.MEDIUM -> level2Questions
            DifficultyLevel.HARD -> level3Questions
        }
        // Randomize question order and randomize choices for each question
        return baseList.shuffled().take(20).map { question ->
            val correctOption = question.options[question.correctIndex]
            val shuffledOptions = question.options.shuffled()
            val newCorrectIndex = shuffledOptions.indexOf(correctOption)
            question.copy(
                options = shuffledOptions,
                correctIndex = newCorrectIndex
            )
        }
    }
